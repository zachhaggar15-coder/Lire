/**
 * Writes docs/review/public-domain-spot-check.md: a deterministic human
 * review sample of the public-domain reading bank (one extract per source
 * per level), the extracts removed on content grounds, and the sources that
 * need a full read-through rather than a sample.
 *
 * Usage: node --import ./scripts/register-alias-loader.mjs scripts/generate-public-domain-spot-check.mjs
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { CONTENT_EXCLUSIONS, SOURCE_META } from "./repair-public-domain-contiguity.mjs";

const { publicDomainTexts: texts } = await import("../src/data/publicDomainTexts.ts");
const provenance = JSON.parse(readFileSync(new URL("../src/data/publicDomainProvenance.json", import.meta.url), "utf8"));
const LEVELS = ["B1", "B2", "C1", "C2"];
// 19th-century travel fiction set in Africa and the colonies: period racial
// framing can appear in any extract, so these need every extract read.
const FULL_REVIEW_SOURCES = [4548, 16826];

const sourceOf = (text) => provenance[text.id].gutenbergId;
const metaOf = (text) => SOURCE_META[sourceOf(text)];
const cell = (value, max) => {
  const flat = value.replace(/\s+/g, " ").trim();
  return (flat.length > max ? `${flat.slice(0, max - 1)}…` : flat).replace(/\|/g, "\\|");
};
const lastSentence = (body) => body.trim().split(/(?<=[.!?…»])\s+/).pop() ?? body;

const sample = [];
for (const level of LEVELS) {
  const seen = new Set();
  for (const text of texts.filter((item) => item.difficulty === level)) {
    const key = `${metaOf(text).title}`;
    if (seen.has(key)) continue;
    seen.add(key);
    sample.push(text);
  }
}

const counts = LEVELS.map((level) => `${level}: ${texts.filter((text) => text.difficulty === level).length}`).join(", ");
const titles = new Set(texts.map((text) => metaOf(text).title));
const lines = [
  "# Public-domain reading bank: human spot-check",
  "",
  `Generated by \`scripts/generate-public-domain-spot-check.mjs\`. Bank: ${texts.length} extracts (${counts}) from ${titles.size} works.`,
  "",
  "Every extract is machine-verified (`node scripts/test-public-domain-provenance.mjs --online`) to be exactly the listed run of paragraphs in the Project Gutenberg edition, unaltered, with no chapter heading or editorial matter inside it. A reviewer should check what a machine cannot:",
  "",
  "1. The extract starts and ends at a sensible point.",
  "2. The content suits a general audience aged 13+ (sexual content, graphic violence, self-harm, slurs, period racism or colonial framing).",
  "3. The level label (B1–C2) is plausible.",
  "4. Title and author are correct.",
  "",
  "Verdicts: OK / Replace / Relabel level / Remove. To remove an extract, add its id and reason to `CONTENT_EXCLUSIONS` in `scripts/repair-public-domain-contiguity.mjs` and re-run that script.",
  "",
  "## Sample: one extract per work per level",
  "",
  "| # | id | Level | Work | Gutenberg | Paragraphs | Words | Opens with | Ends with | Verdict |",
  "|---|---|---|---|---|---|---|---|---|---|",
  ...sample.map((text, index) => {
    const record = provenance[text.id];
    const meta = metaOf(text);
    return `| ${index + 1} | ${text.id} | ${text.difficulty} | ${meta.title} (${meta.author}) | [${record.gutenbergId}](https://www.gutenberg.org/ebooks/${record.gutenbergId}) | ${record.firstParagraph}–${record.lastParagraph} | ${record.words} | ${cell(text.body, 70)} | ${cell(lastSentence(text.body), 60)} |  |`;
  }),
  "",
  "## Full read-through required",
  "",
  "These works are 19th-century adventure fiction set in Africa and colonial territories. An automated screen found and removed extracts with racial slurs, but period framing of non-European peoples can appear without any keyword. Read every extract:",
  "",
  ...FULL_REVIEW_SOURCES.map((gid) => {
    const ids = texts.filter((text) => sourceOf(text) === gid).map((text) => text.id);
    return `- **${SOURCE_META[gid].title}** (${ids.length}): ${ids.join(", ")}`;
  }),
  "",
  "## Removed on content grounds",
  "",
  "| id | Reason |",
  "|---|---|",
  ...Object.entries(CONTENT_EXCLUSIONS).map(([id, reason]) => `| ${id} | ${reason} |`),
  "",
];

mkdirSync(new URL("../docs/review/", import.meta.url), { recursive: true });
writeFileSync(new URL("../docs/review/public-domain-spot-check.md", import.meta.url), lines.join("\n"));
console.log(`spot-check: ${sample.length} sampled, ${FULL_REVIEW_SOURCES.length} works for full review`);
