/**
 * Writes docs/review/french-human-review.md from the live grammar content:
 * every lesson (explanation, pattern, common mistake, all examples with
 * translations and notes) and every practice question (sentence, choices,
 * key, explanation), each with a reviewer checkbox and correction field.
 *
 *   node --import ./scripts/register-alias-loader.mjs scripts/generate-french-review.mjs
 *
 * Machine review is complete; native/qualified sign-off is not, and this
 * document must not be read as saying otherwise.
 */

import { writeFileSync } from "node:fs";

const grammar = await import("../src/lib/grammar.ts");
const lessons = [...grammar.VERB_LESSONS, ...grammar.STRUCTURE_LESSONS];
const questions = grammar.GRAMMAR_QUESTIONS;
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

// Items where more than one French form is acceptable, or where the rule is
// a simplification a reviewer should confirm (from the independent QA).
const ATTENTION = {
  "si-clauses-real-2": "Present (tu peux) is also correct; the question targets the future, and the explanation says so.",
  "futur-anterieur-4": "« Dès que les enfants feront leurs valises » is also possible French (sequence vs simultaneity); not offered as a choice.",
  "adverb-placement-3": "« Il a poliment répondu » is grammatical (stylistic); not offered as a choice; explanation mentions it.",
  "relative-pronouns-advanced-4": "« avec lesquels » is also correct (formal); not offered; explanation mentions it.",
  "reported-speech-1": "Present can remain when the statement is still true; explanation mentions it.",
  "reported-speech-2": "Future can remain when the event is still to come; explanation mentions it.",
  "demonstratives-and-possessives-3": "Rewritten from « la sienne de son frère » (ungrammatical) to « celle de son frère ».",
};
const LESSON_NOTES = {
  "present-ir-re": "Stem rule corrected: vendre drops -re (vend-).",
  imparfait: "Added: être → ét-; -ger/-cer spelling only before a.",
  "future-simple": "Added: -re verbs drop the final e (vendrai).",
  "subjonctif-present-formation": "Corrected: que alone does not mark the subjunctive.",
  "participe-present-gerondif": "Corrected: invariant participle vs agreeing -ant adjective; étant/ayant/sachant.",
  "si-clauses-real": "Scoped: no future after si only when si = if (condition), not whether.",
  "relative-pronoun-dont": "Scoped: only the de that dont replaces is not repeated.",
  "preposition-verb-pairings": "Corrected: penser de is not limited to questions.",
  "object-pronouns-cod": "Added: before an infinitive; after positive commands (lis-le).",
  "voix-passive": "Added: passive vs state (la porte est fermée).",
  "passe-compose": "Added: reflexive agreement exception (s'est lavé les mains).",
  "reported-speech": "Added: still-true statements may keep their tense.",
  "pronoms-toniques": "Added: moi aussi / pas moi; lui is also an indirect object pronoun.",
};

const lines = [];
const push = (...l) => lines.push(...l);
push(
  "# French content: human review package",
  "",
  "> **MACHINE REVIEW COMPLETE — HUMAN/NATIVE SIGN-OFF REQUIRED.**",
  "> Sorlio's French has been checked automatically (accents, elision, answer keys, the independent",
  "> QA's semantic findings; `scripts/test-french-content.mjs`). No native speaker or qualified",
  "> teacher has signed it off yet. Nothing in the app or store listing may claim the content is",
  "> linguistically verified until every row below has a reviewer verdict.",
  "",
  `Generated by \`scripts/generate-french-review.mjs\` from \`src/lib/grammar.ts\`: ${lessons.length} lessons, ${lessons.reduce((n, l) => n + l.examples.length, 0)} examples, ${questions.length} practice questions.`,
  "",
  "## How to review",
  "",
  "For each item: tick **OK**, or write the correction (French, English, explanation or level) in the correction field. Flag anything that is grammatical but unnatural, any translation that is not faithful, and any level (A1–C1) that looks wrong. Items marked ⚠ have more than one acceptable answer or a rule that is a deliberate simplification: confirm the chosen wording.",
  "",
  "Reviewer name: ______________________ Qualification: ______________________ Date: __________",
  "",
  "## Lessons",
  "",
);
for (const lesson of lessons) {
  push(`### ${lesson.title} \`${lesson.id}\` (${lesson.level})`, "");
  if (LESSON_NOTES[lesson.id]) push(`⚠ Changed in machine review: ${LESSON_NOTES[lesson.id]}`, "");
  push(`**Explanation.** ${lesson.explanation}`, "");
  push(`**Pattern.** ${lesson.pattern ?? lesson.corePattern ?? ""}`, "");
  push(`**Common mistake.** ${lesson.commonMistake}`, "");
  push("| Example (French) | English | Note | OK | Correction |", "|---|---|---|---|---|");
  for (const example of lesson.examples) push(`| ${cell(example.french)} | ${cell(example.english)} | ${cell(example.note)} | ☐ | |`);
  push("", "Lesson text OK ☐  Correction: ________________________________________", "");
}
push("## Practice questions", "", "| # | id | Sentence | Choices | Key | Explanation | ⚠ | OK | Correction |", "|---|---|---|---|---|---|---|---|---|");
questions.forEach((q, i) => {
  push(`| ${i + 1} | ${q.id} | ${cell(q.sentence)} | ${cell(q.choices.join(" / "))} | ${cell(q.answer)} | ${cell(q.explanation)} | ${cell(ATTENTION[q.id] ?? "")} | ☐ | |`);
});
push(
  "",
  "## Verb reference tables",
  "",
  `${grammar.VERB_REFERENCES.length} conjugation tables (src/lib/grammar.ts, VERB_REFERENCES). Check every form; accents and stems are machine-checked only.`,
  "",
  ...grammar.VERB_REFERENCES.map((verb) => `- **${verb.infinitive}**: ${Object.entries(verb.forms).map(([tense, forms]) => `${tense}: ${forms.join(", ")}`).join(" · ")} ☐`),
  "",
  "## Sign-off",
  "",
  "☐ All lessons, examples, questions and tables reviewed; corrections above applied and re-reviewed.",
  "",
  "Signed: ______________________ Date: __________",
  "",
);
writeFileSync(new URL("../docs/review/french-human-review.md", import.meta.url), lines.join("\n"));
console.log(`french review: ${lessons.length} lessons, ${questions.length} questions`);
