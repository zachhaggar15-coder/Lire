/**
 * Precomputes the journey ladder's intrinsic difficulty per starter text
 * (src/data/generated/journeyDifficulty.ts), so the app does not tokenise
 * and dictionary-check every starter text on each device at start-up.
 *
 * Scores with the curated dictionary only, as clients did: they built the
 * ladder on first render, before the broad dictionary had loaded, so this
 * keeps every existing learner's route order unchanged. Run in a fresh
 * process for that reason (test-core-logic runs `--check` this way).
 *
 *   node --import ./scripts/register-alias-loader.mjs scripts/generate-journey-difficulty.mjs [--check]
 */
import { readFileSync, writeFileSync } from "node:fs";

const { computeIntrinsicDifficulties } = await import("../src/lib/journey/ladder.ts");
const { isGeneratedDictionaryReady } = await import("../src/lib/dictionary/lookup.ts");

if (isGeneratedDictionaryReady()) throw new Error("broad dictionary already loaded; scores would differ from clients");
const values = computeIntrinsicDifficulties();
const lines = Object.entries(values)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([id, value]) => `  ${JSON.stringify(id)}: ${value},`);
const rendered = [
  "// Generated by scripts/generate-journey-difficulty.mjs. Do not edit.",
  "export const JOURNEY_DIFFICULTY: Record<string, number> = {",
  ...lines,
  "};",
  "",
].join("\n");
const target = new URL("../src/data/generated/journeyDifficulty.ts", import.meta.url);

if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== rendered) {
    console.error("journeyDifficulty.ts is stale: run scripts/generate-journey-difficulty.mjs");
    process.exit(1);
  }
  console.log(`journey difficulty current: ${lines.length} texts`);
} else {
  writeFileSync(target, rendered);
  console.log(`journey difficulty: ${lines.length} texts`);
}
