export function normalizeGrammarAnswer(value: string): string {
  return value.trim().toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/\s+/g, " ");
}

export function isGrammarAnswerCorrect(question: GrammarPracticeQuestion, answer: string): boolean {
  return normalizeGrammarAnswer(question.answer) === normalizeGrammarAnswer(answer);
}

export function recordGrammarAnswer(lessonId: string, questionId: string, correct: boolean): GrammarProgressRecord {
  const now = new Date().toISOString();
  const lesson = getAnyGrammarLesson(lessonId);
  const records = getGrammarProgress();
  const current = records.find((record) => record.lessonId === lessonId) ?? getLessonProgress(lessonId);
  const attempts = current.attempts + 1;
  const correctCount = current.correct + (correct ? 1 : 0);
  const mastery = Math.min(100, Math.round((correctCount / attempts) * 70 + Math.min(30, attempts * 5)));
  const next: GrammarProgressRecord = {
    ...current,
    domain: lesson.domain,
    attempts,
    correct: correctCount,
    mastery,
    completed: current.completed,
    lastPracticedAt: now,
    updatedAt: now,
  };
  persist(PROGRESS_KEY, [next, ...records.filter((record) => record.lessonId !== lessonId)]);
  persist(EVENTS_KEY, [
    { id: `${lessonId}:${questionId}:${now}`, lessonId, questionId, correct, answeredAt: now },
    ...getGrammarPracticeEvents(),
  ].slice(0, 500));
  return next;
}

export function markGrammarLessonComplete(lessonId: string): GrammarProgressRecord {
  const now = new Date().toISOString();
  const lesson = getAnyGrammarLesson(lessonId);
  const records = getGrammarProgress();
  const current = records.find((record) => record.lessonId === lessonId) ?? getLessonProgress(lessonId);
  const next: GrammarProgressRecord = {
    ...current,
    domain: lesson.domain,
    completed: true,
    updatedAt: now,
  };
  persist(PROGRESS_KEY, [next, ...records.filter((record) => record.lessonId !== lessonId)]);
  return next;
}

/**
 * Shared implementation behind buildGrammarDashboard/buildStructureDashboard
 * — each track computes its own totals/mastery/next-lesson/recent-events
 * independently, scoped to its own lesson list, so the two tracks' progress
 * never bleeds into each other.
 */
function buildDashboardFor<T extends GrammarLesson>(
  lessons: T[],
  progress: GrammarProgressRecord[],
  events: GrammarPracticeEvent[]
): GrammarDashboard {
  const byLesson = new Map(progress.map((record) => [record.lessonId, record]));
  const completedLessons = lessons.filter((lesson) => byLesson.get(lesson.id)?.completed).length;
  const averageMastery = Math.round(lessons.reduce((sum, lesson) => sum + (byLesson.get(lesson.id)?.mastery ?? 0), 0) / lessons.length);
  const nextLesson = lessons.find((lesson) => !byLesson.get(lesson.id)?.completed) ?? lessons[lessons.length - 1];
  const practiced = lessons.filter((lesson) => (byLesson.get(lesson.id)?.attempts ?? 0) > 0);
  const strongestLesson = practiced.length === 0 ? null : [...practiced].sort((a, b) => (byLesson.get(b.id)?.mastery ?? 0) - (byLesson.get(a.id)?.mastery ?? 0))[0];
  const weakestLesson = practiced.length === 0 ? null : [...practiced].sort((a, b) => (byLesson.get(a.id)?.mastery ?? 0) - (byLesson.get(b.id)?.mastery ?? 0))[0];
  const lessonIds = new Set(lessons.map((lesson) => lesson.id));
  return {
    totalLessons: lessons.length,
    completedLessons,
    averageMastery,
    nextLesson,
    strongestLesson,
    weakestLesson,
    recentEvents: events
      .filter((event) => lessonIds.has(event.lessonId))
      .sort((a, b) => new Date(b.answeredAt).getTime() - new Date(a.answeredAt).getTime())
      .slice(0, 8),
  };
}

export function buildGrammarDashboard(progress = getGrammarProgress(), events = getGrammarPracticeEvents()): GrammarDashboard {
  return buildDashboardFor(VERB_LESSONS, progress, events);
}

export function buildStructureDashboard(progress = getGrammarProgress(), events = getGrammarPracticeEvents()): GrammarDashboard {
  return buildDashboardFor(STRUCTURE_LESSONS, progress, events);
}

function nextUnlockedLesson<T extends { id: string }>(lessons: T[], progress: GrammarProgressRecord[]): T {
  const completed = new Set(progress.filter((record) => record.completed).map((record) => record.lessonId));
  return lessons.find((lesson) => !completed.has(lesson.id)) ?? lessons[lessons.length - 1];
}

export function currentUnlockedLesson(progress = getGrammarProgress()): VerbLesson {
  return nextUnlockedLesson(VERB_LESSONS, progress);
}

export function currentUnlockedStructureLesson(progress = getGrammarProgress()): StructureLesson {
  return nextUnlockedLesson(STRUCTURE_LESSONS, progress);
}

