/** Resolves a lesson id against either track — used where the caller doesn't know (or care) which track a lessonId belongs to. */
function getAnyGrammarLesson(lessonId: string): GrammarLesson {
  return (
    VERB_LESSONS.find((lesson) => lesson.id === lessonId) ??
    STRUCTURE_LESSONS.find((lesson) => lesson.id === lessonId) ??
    VERB_LESSONS[0]
  );
}

export function getGrammarProgress(): GrammarProgressRecord[] {
  return readArray(PROGRESS_KEY, isProgressRecord);
}

export function getGrammarPracticeEvents(): GrammarPracticeEvent[] {
  return readArray(EVENTS_KEY, isPracticeEvent);
}

export function getLessonProgress(lessonId: string): GrammarProgressRecord {
  const existing = getGrammarProgress().find((record) => record.lessonId === lessonId);
  if (existing) return existing;
  return {
    id: lessonId,
    lessonId,
    domain: getAnyGrammarLesson(lessonId).domain,
    attempts: 0,
    correct: 0,
    completed: false,
    mastery: 0,
    lastPracticedAt: null,
    updatedAt: "",
  };
}

